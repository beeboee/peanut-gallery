const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const classes=new Map();
const context={HTMLElement:class {}, window:{localStorage:{getItem(){},setItem(){}},customCards:[],setTimeout(){},clearTimeout(){},requestAnimationFrame(){}},customElements:{get:n=>classes.get(n),define:(n,c)=>classes.set(n,c)},Date,Set,URL,document:{}};
vm.runInNewContext(readFileSync(process.argv[2]||'custom_components/peanut_gallery/www/peanut-gallery-card-base.js','utf8'),context);
const Card=classes.get('peanut-gallery-card');
function card(width=2800){
 const c=new Card(), flags=new Set();
 const root={classList:{contains(n){return flags.has(n)},toggle(n,on){on?flags.add(n):flags.delete(n)}}};
 const scroll={scrollWidth:width,clientWidth:1000,scrollLeft:0,hidden:false};
 c.$=s=>s==='ha-card'?root:s==='.comic-scroll'?scroll:null;
 c.controlsVisible=true;c.actionInProgress=false;c.config={};c.getImageSrc=()=> 'comic';
 return {c,scroll,flags};
}
const initial=card();
initial.c.shadowRoot={};
initial.c.renderBase=()=>{};
initial.c.setConfig({card_id:'startup'});
initial.c.updateReadingControls();
assert.equal(initial.flags.has('controls-hidden'),true,'UI starts hidden');
initial.c.toggleControls();
assert.equal(initial.flags.has('controls-hidden'),false,'first tap shows UI');
initial.c.updateReadingControls();
assert.equal(initial.flags.has('controls-hidden'),false,'updates preserve the visible UI choice');
initial.c.toggleControls();
assert.equal(initial.flags.has('controls-hidden'),true,'second tap hides UI');
const {c,scroll,flags}=card();
c.runAction=()=>Promise.resolve();
c.showNext();
assert.equal(c.controlsVisible,false,'Next must hide UI');
c.updateReadingControls();
assert.equal(flags.has('reading-action-visible'),false,'start stays hidden');
scroll.scrollLeft=1800;c.updateReadingControls();
assert.equal(flags.has('reading-action-visible'),true,'end shows action');
c.toggleControls();c.updateReadingControls();
assert.equal(c.controlsVisible,false,'first tap hides only action');
assert.equal(flags.has('reading-action-visible'),false);
scroll.scrollLeft=0;c.updateReadingControls();scroll.scrollLeft=1800;c.updateReadingControls();
assert.equal(flags.has('reading-action-visible'),false,'scroll cannot override tap');
c.toggleControls();assert.equal(c.controlsVisible,true,'second tap restores normal UI');
const fit=card(1000);fit.c.runAction=()=>Promise.resolve();fit.c.showRandom();fit.c.updateReadingControls();
assert.equal(fit.c.controlsVisible,false);
assert.equal(fit.flags.has('reading-action-visible'),false,'fitting comic stays hidden');
fit.c.toggleControls();assert.equal(fit.c.controlsVisible,true);
console.log('Reading controls scenarios passed');
const busy=card();busy.c.actionInProgress=true;busy.c.showNext();
assert.equal(busy.c.controlsVisible,true,'busy navigation cannot change controls');
c.beginReading();scroll.scrollLeft=1800;c.imageLoading=true;c.updateReadingControls();
assert.equal(flags.has('reading-action-visible'),false,'loading images cannot reveal stale action');
c.imageLoading=false;c.updateReadingControls();assert.equal(flags.has('reading-action-visible'),true);
scroll.scrollLeft=100;c.updateReadingControls();
assert.equal(flags.has('reading-action-visible'),false,'leaving end hides action');
scroll.scrollWidth=1000;c.updateReadingControls();
assert.equal(flags.has('reading-action-visible'),false,'resize to fit stays hidden');
